# Update-WaxFrame.ps1
#
# Companion updater for the WaxFrame Professional portable (file://) install.
# Start it by double-clicking Update-WaxFrame.cmd in this WaxFrame folder (a
# plain launcher for this script), or right-click this file -> "Run with
# PowerShell". Cannot be launched automatically from the browser tab --
# a file:// page has no way to execute a local script, by design (see
# js/update-check.js, which only ever shows instructions pointing here).
#
# What this does: checks GitHub for a newer release, downloads it, checks
# the download is structurally sound, and swaps it in -- keeping your
# current install as a dated backup folder next to this one. If anything
# goes wrong partway through, it rolls back automatically so you're never
# left without a working copy.
#
# Backups: once two or more backup folders exist, the script asks how many
# of the most recent to keep (Enter keeps all of them, which is the
# default). Older backups hold exactly what those older versions shipped.
# To answer without the prompt, run with -KeepBackups N, or set the
# environment variable WAXFRAME_KEEP_BACKUPS=N. N=0 removes every backup.
#
# Deliberate scope decisions (not gaps -- stated up front):
#   - This script targets Windows/PowerShell. Mac/Linux portable installs
#     use the sibling Update-WaxFrame.command script.
#   - Release ZIPs are manually named assets generated by the release-assets
#     workflow. A separately downloaded SHA-256 manifest is required and
#     verified before extraction. GitHub also publishes a signed build-
#     provenance attestation for the ZIP; when the GitHub CLI (gh) is
#     installed it is verified too, and a failed check refuses the update.
#     Without gh the SHA-256 and the `gh attestation verify` command are
#     printed so it can be run by hand.
#   - No user-data migration step. WaxFrame keeps everything you create
#     in the browser (IndexedDB/localStorage) or in a folder you pick
#     yourself via a save dialog -- never inside this app folder. So the
#     whole folder is safe to rename/replace wholesale.
#   - No running-process coordination. A file:// page isn't a process to
#     wait on or restart -- "relaunch" just means reopening index.html.
#
# Build: 20261114-002

[CmdletBinding()]
param(
  # -1 = ask (the default). 0 or more = keep that many of the most recent
  # backup folders and remove the rest, without prompting.
  [int]$KeepBackups = -1
)

$ErrorActionPreference = 'Stop'
$Repo = 'WeirDave/WaxFrame-Professional'

function Write-Step($msg) { Write-Host $msg -ForegroundColor Cyan }
function Write-Ok($msg)   { Write-Host $msg -ForegroundColor Green }
function Write-Err($msg)  { Write-Host $msg -ForegroundColor Red }
function Write-Warn($msg) { Write-Host $msg -ForegroundColor Yellow }

function Compare-WfVersion($a, $b) {
  $pa = ($a -replace '^v', '') -split '\.' | ForEach-Object { [int]($_ -as [int]) }
  $pb = ($b -replace '^v', '') -split '\.' | ForEach-Object { [int]($_ -as [int]) }
  $len = [Math]::Max($pa.Count, $pb.Count)
  for ($i = 0; $i -lt $len; $i++) {
    $av = if ($i -lt $pa.Count) { $pa[$i] } else { 0 }
    $bv = if ($i -lt $pb.Count) { $pb[$i] } else { 0 }
    if ($av -gt $bv) { return 1 }
    if ($av -lt $bv) { return -1 }
  }
  return 0
}

function Get-WfVersion($root) {
  $versionFile = Join-Path $root 'js\version.js'
  if (-not (Test-Path $versionFile)) { return $null }
  $content = Get-Content -Raw -LiteralPath $versionFile
  if ($content -match "const\s+APP_VERSION\s*=\s*['""]v?([\d.]+)\s+Pro['""]") {
    return $Matches[1]
  }
  return $null
}

# ---- Download safety helpers ------------------------------------------------
# Kept identical in Install-WaxFrame.ps1 (an irm | iex script cannot dot-source
# a shared file).

# The SHA-256 sidecar is published in the same release as the ZIP, so on its
# own it only proves the download was not corrupted. When the GitHub CLI is
# installed, also check the build-provenance attestation the release workflow
# signs. A failed check refuses the download. Without gh the checksum still
# stands, and the exact command is printed so it can be run by hand.
function Confirm-WfAttestation($zip, $assetName, $sha256) {
  $gh = Get-Command gh -CommandType Application -ErrorAction SilentlyContinue
  if (-not $gh) {
    Write-Warn "GitHub CLI (gh) not found -- build provenance was not checked, only the SHA-256."
    Write-Warn "  SHA-256 of $assetName : $sha256"
    Write-Warn "  To verify it independently: gh attestation verify $assetName --repo $Repo"
    return
  }
  # gh writes progress to stderr; under 'Stop' that would throw on success.
  $prevEap = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    $output = & gh attestation verify $zip --repo $Repo 2>&1
    $code = $LASTEXITCODE
    $loggedIn = $true
    if ($code -ne 0) {
      & gh auth status *>$null
      $loggedIn = ($LASTEXITCODE -eq 0)
    }
  } finally { $ErrorActionPreference = $prevEap }
  if ($code -eq 0) { Write-Ok "Build provenance verified (gh attestation)."; return }
  if (-not $loggedIn) {
    # gh needs a login to fetch attestations. Not logged in is "could not
    # check", not "checked and failed", so behave as if gh were absent.
    Write-Warn "GitHub CLI is installed but not signed in, so build provenance was not checked."
    Write-Warn "  SHA-256 of $assetName : $sha256"
    Write-Warn "  After 'gh auth login': gh attestation verify $assetName --repo $Repo"
    return
  }
  throw "Build provenance check failed (gh attestation verify) -- the download was not used. $((@($output | ForEach-Object { if ($_ -is [System.Management.Automation.ErrorRecord]) { $_.Exception.Message } else { "$_" } } | Where-Object { $_ }) -join ' ').Trim())"
}

# Refuse an archive before extracting any of it: no entry may climb out of the
# destination ('..' segments), be absolute, carry a drive letter / stream
# colon, or be a symbolic link. Windows PowerShell 5.1 compatible.
function Test-WfZipEntries($zip) {
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $archive = [System.IO.Compression.ZipFile]::OpenRead($zip)
  try {
    foreach ($entry in $archive.Entries) {
      $norm = $entry.FullName -replace '\\', '/'
      if ($norm.StartsWith('/') -or $norm.Contains(':') -or $norm -match '(^|/)\.\.(/|$)') {
        throw "Release archive contains an unsafe path: $($entry.FullName)"
      }
      # The Unix mode lives in the top 16 bits of the external attributes.
      if ((([int64]$entry.ExternalAttributes -shr 16) -band 0xF000) -eq 0xA000) {
        throw "Release archive contains a symbolic link: $($entry.FullName)"
      }
    }
  } finally { $archive.Dispose() }
}

# After extraction: the root must still sit under the staging folder and the
# tree must hold no reparse points (junctions / symlinks).
function Assert-WfExtractedSafe($root, $stage) {
  $sep = [IO.Path]::DirectorySeparatorChar
  $stageFull = [IO.Path]::GetFullPath($stage).TrimEnd('\', '/') + $sep
  $rootFull = [IO.Path]::GetFullPath($root)
  if (-not (($rootFull.TrimEnd('\', '/') + $sep).StartsWith($stageFull, [StringComparison]::OrdinalIgnoreCase))) {
    throw "Extracted release root is outside the staging folder: $rootFull"
  }
  $link = Get-ChildItem -LiteralPath $root -Recurse -Force |
    Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint } | Select-Object -First 1
  if ($link) { throw "Extracted release contains a link: $($link.FullName)" }
}

$RequiredFiles = @(
  'index.html', 'ai-api-pricing.html', 'ai-business-proposal.html', 'ai-cover-letter-editor.html',
  'ai-resume-review.html', 'api-details.html', 'document-playbooks.html', 'help.html',
  'hive-profiles.html', 'privacy.html', 'prompt-editor.html', 'start-here.html',
  'templates.html', 'terms.html', 'waxframe-user-manual.html', 'what-are-tokens.html',
  'js\version.js', 'js\app.js', 'style.css'
)

function Test-WfReleaseTree($root, $expectedVersion) {
  foreach ($f in $RequiredFiles) {
    if (-not (Test-Path (Join-Path $root $f))) {
      throw "Downloaded release is missing expected file: $f"
    }
  }
  $ver = Get-WfVersion $root
  if (-not $ver) { throw "Downloaded release: could not read APP_VERSION from js\version.js" }
  if ($expectedVersion -and ($ver -ne $expectedVersion)) {
    throw "Downloaded release version mismatch: expected $expectedVersion, found $ver"
  }
  return $ver
}

# ---- 1. Resolve install root + current version ------------------------------
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not (Test-Path (Join-Path $scriptDir 'index.html'))) {
  Write-Err "This script must run from inside a WaxFrame install folder (index.html not found next to it)."
  Read-Host "Press Enter to close"
  exit 1
}
$currentVersion = Get-WfVersion $scriptDir
if (-not $currentVersion) {
  Write-Err "Could not read the current version from js\version.js."
  Read-Host "Press Enter to close"
  exit 1
}
Write-Step "WaxFrame Professional updater -- currently v$currentVersion"

# Step out of the install folder before anything else. Explorer (and any
# terminal opened here) starts this script with the install folder as its
# working directory, and Windows will not rename a folder that is some
# process's working directory -- step 8's swap would stop with "in use".
Set-Location -LiteralPath $env:TEMP
[Environment]::CurrentDirectory = $env:TEMP

# ---- 2. Check latest release --------------------------------------------------
Write-Step "Checking for updates..."
try {
  $release = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repo/releases/latest" `
    -Headers @{ Accept = 'application/vnd.github+json' } -UseBasicParsing
} catch {
  Write-Err "Could not reach GitHub to check for updates: $($_.Exception.Message)"
  Read-Host "Press Enter to close"
  exit 1
}
$latestTag = [string]$release.tag_name
$latestVersion = $latestTag -replace '^v', ''
if ($latestTag -notmatch '^v[0-9]+(?:\.[0-9]+)+$') {
  Write-Err "GitHub returned an unexpected release tag: $latestTag"
  Read-Host "Press Enter to close"
  exit 1
}
if ((Compare-WfVersion $latestVersion $currentVersion) -le 0) {
  Write-Ok "Already up to date (v$currentVersion)."
  Read-Host "Press Enter to close"
  exit 0
}
Write-Ok "v$latestVersion is available (you have v$currentVersion)."

# ---- 2b. Git fast path ---------------------------------------------------------
# A folder cloned from GitHub updates by fetching and checking out the release
# tag: a few KB of objects instead of the whole ZIP, and the previous version
# stays in the object store as its own rollback. The ZIP path below is
# unchanged and still handles every other install.
#
# Refuses on a working copy with unpushed commits or edited tracked files --
# checking a release tag out over in-progress work is not an update.
function Test-WfGit {
  try { & git --version *>$null; return $LASTEXITCODE -eq 0 } catch { return $false }
}

function Invoke-WfGit {
  param([string[]]$Arguments, [switch]$AllowFailure)
  # Windows PowerShell 5.1 raises a terminating error for any native stderr line
  # under $ErrorActionPreference = 'Stop' (git writes progress and "From ..." lines
  # there on success). The exit code below is the real signal.
  $prevEap = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try { $output = & git -C $scriptDir @Arguments 2>&1 } finally { $ErrorActionPreference = $prevEap }
  if ($LASTEXITCODE -ne 0 -and -not $AllowFailure) {
    throw "git $($Arguments -join ' ') failed: $output"
  }
  return $output
}

function Get-WfDirtyTrackedPaths {
  $lines = Invoke-WfGit -Arguments @('status', '--porcelain') -AllowFailure
  $dirty = @()
  foreach ($line in @($lines)) {
    $text = "$line"
    if ($text.Trim().Length -eq 0) { continue }
    if ($text.Substring(0, 2).Trim() -eq '??') { continue }  # untracked never blocks
    $dirty += $text.Substring(3).Trim().Trim('"')
  }
  return $dirty
}

if ((Test-Path (Join-Path $scriptDir '.git')) -and (Test-WfGit)) {
  Write-Step 'This copy is a git checkout -- updating with git.'
  try {
    $head = (Invoke-WfGit -Arguments @('rev-parse', '--abbrev-ref', 'HEAD') -AllowFailure | Out-String).Trim()
    $onBranch = $head -and $head -ne 'HEAD'
    $ahead = 0
    if ($onBranch) {
      $aheadText = (Invoke-WfGit -Arguments @('rev-list', '--count', '@{u}..HEAD') -AllowFailure | Out-String).Trim()
      if ($aheadText -match '^\d+$') { $ahead = [int]$aheadText }
    }
    $dirty = Get-WfDirtyTrackedPaths

    if ($onBranch -and ($ahead -gt 0 -or $dirty.Count -gt 0)) {
      Write-Err 'This checkout has local work -- unpushed commits or edited files.'
      Write-Err 'Updating would check a release tag out over it. Use git directly.'
      Read-Host 'Press Enter to close'
      exit 1
    }
    if ($dirty.Count -gt 0) {
      Write-Err "These tracked files have local edits: $($dirty -join ', ')"
      Write-Err 'Revert or move them, then run this again.'
      Read-Host 'Press Enter to close'
      exit 1
    }

    Write-Step 'Fetching from GitHub...'
    Invoke-WfGit -Arguments @('fetch', '--tags', '--prune', 'origin') | Out-Null
    Write-Step "Checking out $latestTag..."
    Invoke-WfGit -Arguments @('-c', 'advice.detachedHead=false', 'checkout', '--force', $latestTag) | Out-Null

    $installedVersion = Get-WfVersion $scriptDir
    Write-Ok "Updated to v$installedVersion. Nothing was downloaded or replaced --"
    Write-Ok "your previous version is still in git if you ever need it back."
    Write-Step 'Reopening WaxFrame...'
    Start-Process (Join-Path $scriptDir 'index.html')
    Read-Host 'Press Enter to close'
    exit 0
  } catch {
    Write-Warn "Git update didn't complete: $($_.Exception.Message)"
    Write-Warn 'Falling back to the download method.'
  }
}

# ---- 3. Download into staging --------------------------------------------------
# Staged OUTSIDE $scriptDir (the download in %TEMP%, the extracted tree next to
# the install folder). Staging inside the install folder would break step 8's
# atomic swap: once $scriptDir gets renamed to the backup name, every path
# computed under it (this staging folder included) would silently move along
# with it, invalidating $extractedRoot mid-run.
$staging = Join-Path $env:TEMP "WaxFrameUpdate-$([guid]::NewGuid().ToString('N'))"
New-Item -ItemType Directory -Path $staging -Force | Out-Null
$zipPath = Join-Path $staging 'download.zip'
$checksumPath = Join-Path $staging 'download.sha256'

# The download stays in %TEMP%, but the extracted tree is staged as a SIBLING
# of the install folder. Step 8 then swaps it in with a same-volume rename.
# Moving it in from %TEMP% copied file by file whenever %TEMP% was on another
# drive, and a copy that died halfway left a partial folder under the install
# name.
$parent = Split-Path -Parent $scriptDir
$folderName = Split-Path -Leaf $scriptDir
$extractPath = Join-Path $parent "$folderName.incoming-$([guid]::NewGuid().ToString('N'))"

function Remove-Staging {
  if (Test-Path $staging) { Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue }
  if (Test-Path -LiteralPath $extractPath) { Remove-Item -LiteralPath $extractPath -Recurse -Force -ErrorAction SilentlyContinue }
}
$swapNote = 'Nothing was left half-installed -- your previous copy is intact.'

try {
  Write-Step "Downloading v$latestVersion..."
  $assetName = "WaxFrame-Professional-$latestVersion.zip"
  $checksumName = "$assetName.sha256"
  $releaseBaseUrl = "https://github.com/$Repo/releases/download/$latestTag"
  $downloadUrl = "$releaseBaseUrl/$assetName"
  $checksumUrl = "$releaseBaseUrl/$checksumName"
  Invoke-WebRequest -Uri $downloadUrl -OutFile $zipPath -UseBasicParsing
  Invoke-WebRequest -Uri $checksumUrl -OutFile $checksumPath -UseBasicParsing

  Write-Step "Verifying SHA-256..."
  $checksumText = (Get-Content -LiteralPath $checksumPath -Raw).Trim()
  if ($checksumText -notmatch '^(?<hash>[A-Fa-f0-9]{64})(?:\s+\*?[^\r\n]+)?$') {
    throw "Release checksum manifest is malformed"
  }
  $expectedHash = $Matches['hash'].ToLowerInvariant()
  $actualHash = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
  if ($actualHash -ne $expectedHash) {
    throw "Release SHA-256 mismatch -- expected $expectedHash, got $actualHash"
  }
  Write-Ok "SHA-256 verified: $actualHash"
  Confirm-WfAttestation $zipPath $assetName $actualHash

  # ---- 4/5. Extract + handle GitHub's wrapper folder --------------------------
  Write-Step "Extracting..."
  Test-WfZipEntries $zipPath
  Expand-Archive -LiteralPath $zipPath -DestinationPath $extractPath -Force
  $children = @(Get-ChildItem -LiteralPath $extractPath -Directory)
  if ($children.Count -ne 1) {
    throw "Unexpected archive layout: expected exactly one top-level folder, found $($children.Count)."
  }
  $extractedRoot = $children[0].FullName
  Assert-WfExtractedSafe $extractedRoot $extractPath

  # ---- 6/7. Validate the already checksum-verified tree structurally -----------
  Write-Step "Verifying..."
  Test-WfReleaseTree $extractedRoot $latestVersion | Out-Null
  Write-Ok "Verified: v$latestVersion, all required files present."

  # ---- 8. Atomic swap with backup ----------------------------------------------
  Write-Step "Installing..."
  $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
  $backupLeaf = "$folderName.previous-$currentVersion-$timestamp"
  $backupPath = Join-Path $parent $backupLeaf

  try {
    Rename-Item -LiteralPath $scriptDir -NewName $backupLeaf -ErrorAction Stop
  } catch {
    throw "The WaxFrame folder is in use by another program. Close any File Explorer windows, terminals or editors open inside it, then run this again. ($($_.Exception.Message))"
  }
  try {
    Move-Item -LiteralPath $extractedRoot -Destination $scriptDir -ErrorAction Stop
  } catch {
    # Roll back: put the original folder's name back so the user is never
    # left without a working copy. A failed move can leave a partial folder
    # under the install name, so clear that out first -- rolling back only
    # when the name was free let a half-copied folder block the restore.
    $moveError = $_.Exception.Message
    if (Test-Path -LiteralPath $backupPath) {
      if (Test-Path -LiteralPath $scriptDir) {
        Remove-Item -LiteralPath $scriptDir -Recurse -Force -ErrorAction SilentlyContinue
      }
      if (-not (Test-Path -LiteralPath $scriptDir)) {
        Rename-Item -LiteralPath $backupPath -NewName $folderName -ErrorAction SilentlyContinue
      }
    }
    if (-not (Test-Path -LiteralPath (Join-Path $scriptDir 'index.html')) -or (Test-Path -LiteralPath $backupPath)) {
      $swapNote = "The automatic rollback did not finish. Your previous copy is at: $backupPath -- rename it back to '$folderName' (delete any partial '$folderName' folder first)."
    }
    throw $moveError
  }

  Write-Ok "Updated to v$latestVersion. Your previous copy is kept at:"
  Write-Ok "  $backupPath"

  # ---- 9. Relaunch ---------------------------------------------------------------
  Write-Step "Reopening WaxFrame..."
  Start-Process (Join-Path $scriptDir 'index.html')

} catch {
  Write-Err "Update failed: $($_.Exception.Message)"
  Write-Err $swapNote
  Read-Host "Press Enter to close"
  exit 1
} finally {
  Remove-Staging
}

# ---- 10. Optional backup pruning -------------------------------------------------
# Runs only after a successful swap, outside the install try/catch so a
# problem here can never be reported as a failed update. Only sibling folders
# named "<this folder>.previous-<version>-<yyyyMMdd-HHmmss>" that contain
# js\version.js are candidates -- nothing else in the parent is ever touched.
try {
  $prefix = "$folderName.previous-"
  $backups = @(Get-ChildItem -LiteralPath $parent -Directory |
    Where-Object {
      $_.Name.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase) -and
      $_.Name -match '-(\d{8}-\d{6})$' -and
      (Test-Path -LiteralPath (Join-Path $_.FullName 'js\version.js'))
    } |
    Sort-Object { ($_.Name -replace '^.*-(\d{8}-\d{6})$', '$1') } -Descending)

  $keep = $KeepBackups
  if ($keep -lt 0 -and $env:WAXFRAME_KEEP_BACKUPS -match '^\d+$') { $keep = [int]$env:WAXFRAME_KEEP_BACKUPS }

  if ($backups.Count -ge 2 -and $keep -lt 0) {
    $bytes = ($backups | ForEach-Object {
      (Get-ChildItem -LiteralPath $_.FullName -Recurse -File -ErrorAction SilentlyContinue | Measure-Object Length -Sum).Sum
    } | Measure-Object -Sum).Sum
    Write-Host ''
    Write-Step ("There are {0} backup folders from earlier updates ({1:N0} MB), newest first:" -f $backups.Count, ($bytes / 1MB))
    $backups | ForEach-Object { Write-Host "  $($_.Name)" }
    Write-Host 'Each one holds exactly what that older version shipped.'
    $answer = Read-Host 'Keep how many of the most recent? (Enter = keep all)'
    if ($answer -match '^\s*(\d+)\s*$') { $keep = [int]$Matches[1] }
  }

  if ($keep -ge 0 -and $backups.Count -gt $keep) {
    foreach ($old in ($backups | Select-Object -Skip $keep)) {
      Remove-Item -LiteralPath $old.FullName -Recurse -Force -ErrorAction Stop
      Write-Ok "Removed backup: $($old.Name)"
    }
  }
} catch {
  Write-Warn "Backup cleanup did not finish: $($_.Exception.Message)"
  Write-Warn 'The update itself succeeded. Any remaining backup folders can be deleted by hand.'
}

Read-Host "Press Enter to close"
